"""Turn the raw 2015-2016 measurement files into js/measures.js.

Usage: python3 -I tools/build_data.py <data_dir> > js/measures.js
<data_dir> holds the CSV exports of the Drive spreadsheets and the HS Laps stopwatch files.
"""
import csv, json, sys, pathlib

d = pathlib.Path(sys.argv[1])
num = lambda s: float(s.replace(",", "."))

def laps(name):
    rows = list(csv.reader(open(d / name), delimiter=";"))[1:]
    out = []
    for _, lap, total in rows:
        hms = lambda t: sum(float(x) * k for x, k in zip(t.split(":"), (3600, 60, 1)))
        out.append([round(hms(total), 3), round(1 / hms(lap), 4)])
    return out

def sheet(name, cols):
    rows = list(csv.reader(open(d / name)))
    out = []
    for r in rows:
        try:
            out.append([round(num(r[cols[0]]), 2), round(num(r[cols[1]]), 4)])
        except (ValueError, IndexError):
            pass
    return out

cond = sheet("conductivite.csv", (2, 3))  # concentration g/L, conductivity S/m
extr = sheet("conductimetrie_1ere.csv", (0, 3))  # time s, conductivity S/m
extr = extr[::4]

data = {
    "conductivity": cond,
    "extraction": extr,
    "friction": {
        "crookes": [laps(f"crookes{i}.csv") for i in (1, 2, 3)],
        "supermag": [laps(f"mag{i}.csv") for i in (1, 2)],
    },
    "thrust": json.load(open(d / "rotation.json")),
}
print("// Generated by tools/build_data.py from the original measurement files (2015-2016).")
print("export const MEASURES = " + json.dumps(data, separators=(",", ":")) + ";")
